# source: evidence.test.js:11 should perform simple GET for evidence
def test_should_perform_simple_get_for_evidence() -> None:
    rb, rec = make_client(respond(200, JS_EVIDENCE_BODY))

    # JS: evidence("thisistheurl", "thisisthesession", "thisisthefact")
    result = rb.evidence(SESSION_ID, FACT_ID)

    # JS: expect(global.fetch).toHaveBeenCalledTimes(1)
    assert len(rec) == 1
    _assert_js_get(rec.last, _evidence_path(FACT_ID, SESSION_ID))
    assert str(rec.last.url) == f"{BASE_URL}{_evidence_path(FACT_ID, SESSION_ID)}"
    # JS: headers toMatchObject({}) -- neither optional header is present without options.
    assert "x-evidence-key" not in rec.last.headers
    assert "x-rainbird-engine" not in rec.last.headers
    _assert_js_ok_body_parsed(result)

    # Python also exposes the same call on a Session; it must send the identical request.
    via_session = rb.resume(SESSION_ID).evidence(FACT_ID)
    assert len(rec) == 2
    _assert_js_get(rec.last, _evidence_path(FACT_ID, SESSION_ID))
    assert via_session == result


