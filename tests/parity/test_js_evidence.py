def _evidence_path(fact_id: str, session_id: str) -> str:
    return f"/analysis/evidence/{fact_id}/{session_id}"


def _assert_js_get(call: Call, path: str) -> None:
    """The request-shape assertions every JS case makes.

    JS: ``Object.keys(call).sort()`` is exactly ``["headers", "method"]`` (so no body),
    ``call.method === "GET"`` and ``call.headers`` matches ``{}``.
    """
    assert call.method == "GET"
    assert call.path == path
    assert call.query == {}
    assert call.content == b""  # no "body" key in the fetch init
    # DIFFERENCE(js): evidence.ts sends no credentials at all (its header object holds only the
    # optional x-rainbird-engine / x-evidence-key); Python sends X-API-Key, User-Agent and Accept
    # on every request and never Authorization. Neither sends Content-Type on this GET.
    assert call.headers["x-api-key"] == API_KEY
    assert "authorization" not in call.headers
    assert "content-type" not in call.headers
    assert call.headers["accept"] == "application/json"
    assert call.headers["user-agent"].startswith("rainbird-ai-python/")


def _assert_js_ok_body_parsed(result: Evidence) -> None:
    """JS: ``expect(result).toEqual({ result: { foo: "bar" } })``.

    DIFFERENCE(js): JS returns the parsed JSON untouched; Python returns an ``Evidence`` whose
    ``.raw`` / ``.to_dict()`` is that JSON. The body has none of the evidence keys, so the model
    is an empty node rather than an echo of ``{"result": ...}``.
    """
    assert isinstance(result, Evidence)
    assert result.raw == JS_EVIDENCE_BODY
    assert result.to_dict() == JS_EVIDENCE_BODY
    assert result.to_dict() is not result.raw  # deep copy
    assert result.fact_id == ""
    assert result.source is None
    assert result.rule is None
    assert result.is_inferred is False
    assert result.child_fact_ids == []
    assert result.time is None


def _serve_by_fact_id(nodes: list[dict[str, Any]], *, root_alias: str) -> Handler:
    """Python-side stand-in for ``json: async () => evidenceFacts[calls - 1]``.

    The JS mock hands out the canned nodes purely by ``json()`` call order, ignoring the id in
    the URL: the root request gets ``evidenceFacts[0]`` and the three child requests (issued in
    condition order 1237, 593a, b20f) receive the 593a, b20f and 1237 bodies respectively, so JS
    never checks that the body for id X was fetched under X. Once the nodes run out it returns
    ``undefined``. Python's walk is order-independent and keyed by the requested id, so this
    handler is stricter than the original: it serves each node by the ``factID`` in the request
    path (``root_alias`` maps the requested root id ``"thisisthefact"`` to the first node) and
    answers a JSON ``null`` body -- the closest HTTP equivalent of ``undefined`` -- for every
    other id.
    """
    by_id = {node["factID"]: node for node in nodes}
    by_id[root_alias] = nodes[0]

    def handler(request: httpx.Request) -> httpx.Response:
        _, analysis, evidence, fact_id, session_id = request.url.path.split("/")
        assert (analysis, evidence, session_id) == ("analysis", "evidence", SESSION_ID)
        node = by_id.get(fact_id)
        if node is None:
            return httpx.Response(
                200, content=b"null", headers={"content-type": "application/json"}
            )
        return httpx.Response(200, json=node)

    return handler


def _session(handler: Handler, session_id: str, **kwargs: Any) -> tuple[Rainbird, Session, Any]:
    rb, rec = make_client(handler, **kwargs)
    return rb, rb.resume(session_id), rec


