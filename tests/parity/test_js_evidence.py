"""Port of the JavaScript base SDK ``evidence`` and ``fullEvidence`` unit tests.

Sources:

* ``packages/base/lib/__tests__/evidence.test.js`` (``describe("evidence")``) and the
  implementation under test ``packages/base/lib/evidence.ts``:

  - should perform simple GET for evidence
  - should GET evidence for alternate engines
  - should throw fetch-generated errors
  - should handle 404 / should handle 500 / should handle 400
  - should call the evidence endpoint with the evidence key header

* ``packages/base/lib/__tests__/full_evidence.test.js`` (``describe("fullEvidence")``; the canned
  ``evidenceFacts`` / ``normalResp`` / ``noRule`` / ``noRuleIncluded`` fixtures at the top of that
  file are copied below) and the implementation ``packages/base/lib/full_evidence.ts``:

  - should perform a simple fullEvidence retrieval
  - should include fact that does not have a rule
  - should throw fetch-generated errors
  - should handle 404

Python counterparts: ``Rainbird.evidence(session_id, fact_id, evidence_key=...)`` and
``Session.evidence(fact_id, evidence_key=...)`` (``GET /analysis/evidence/{factID}/{sessionID}``)
returning :class:`rainbird_ai.models.Evidence`; ``Session.evidence_tree(fact_id)`` /
``Session.iter_evidence_tree(fact_id)`` for ``fullEvidence``. Two adapted cases cover behaviour
the JS mocks only touch implicitly: the unbounded walk over the ``undefined`` leaf bodies and the
client-wide evidence key.

Differences found (each is asserted next to a ``DIFFERENCE(js)`` comment):

- Auth/headers: JS ``evidence`` sends no credentials (only the optional ``x-rainbird-engine`` and
  ``x-evidence-key``); Python sends ``X-API-Key``, ``User-Agent`` and ``Accept`` on every request
  and never ``Authorization``. Neither sends ``Content-Type`` on this body-less GET.
- Engine: JS passes ``{engine}`` per call; Python sets it once with ``Rainbird(engine=...)`` and
  sends ``x-rainbird-engine`` on every request. ``rainbird_ai.ENGINE_BETA`` carries the same
  string as JS's ``ENGINE_BETA`` (since 1.1.0).
- Return value: JS returns the parsed JSON untouched; Python returns an ``Evidence`` model that
  keeps the JSON on ``.raw`` / ``.to_dict()``, so the canned ``{"result": {"foo": "bar"}}`` body
  parses to an empty node (``fact_id == ""``, ``rule is None``) instead of being echoed back.
- Errors: JS throws ``Error("API error code: N")`` or re-throws the fetch error unchanged; Python
  raises ``NotFoundError`` / ``ServerError`` / ``BadRequestError`` (``.status_code``, a default
  ``.message`` because the ``{}`` body carries no text, ``.body``, ``.errors``, ``.method``,
  ``.url``) and wraps the transport failure in ``RainbirdConnectionError`` whose message embeds
  the original text after the method and URL.
- ``fullEvidence`` walk: JS recurses concurrently, silently skips any falsy body
  (``if (!factEvidence) return []``) and accumulates nodes in a *module-level* ``Map`` keyed by
  the body's ``factID`` that is never cleared. With the sequential mock that means 10 fetches
  (6 answered with ``undefined``) yield 4 nodes, and the next test sees those 4 plus its own.
  Python walks breadth-first, root first, keyed by the *requested* id, one fresh walk per call,
  and cannot skip a node: a 200 with a JSON ``null`` body raises ``UnexpectedResponseError``.
  The simple-retrieval port therefore bounds the walk with ``max_depth=1`` to obtain exactly the
  4 canned nodes (4 requests instead of 10); an adapted case shows the unbounded walk failing on
  the first ``null`` leaf after 5 requests while ``iter_evidence_tree`` still yields the 4 nodes.
- Ordering: JS's ``Map`` order follows promise resolution; Python's list is the root followed by
  its ``child_fact_ids`` in condition order, so equality is asserted on the set of nodes.
"""

