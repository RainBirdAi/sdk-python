"""Port of the JavaScript base SDK ``inject`` unit tests to the Python SDK.

Source: ``packages/base/lib/__tests__/inject.test.js`` (``describe("inject")``) and the
implementation under test ``packages/base/lib/inject.ts``. Every ``it(...)`` case is ported, with
the adaptations listed below, driving ``Session.inject`` (``POST /{sessionID}/inject``) against a
fake ``httpx`` transport with the original canned request and response bodies:

- should assert a new fact within a session
- should assert facts within a session
- should assert a facts for specific engine within a session
- should throw fetch-generated errors (parametrised over the httpx transport-error family)
- should handle 404
- should handle 500
- should handle 400

Two extra cases, not in the JS suite, cover the ``InjectResponse`` TypeScript interface in
``inject.ts`` (``result`` + optional ``warningLog``) and pin the lenient ``InjectResponse.ok``
rule for the nested ``{"response": {"ok": false}}`` shape the JS mock body suggests.

Not portable: the jest ``expect(Object.keys(call).sort()).toEqual(["body", "headers", "method"])``
check on the fetch init object has no httpx analogue (an ``httpx.Request`` is not a plain dict of
init options); method, headers and body are asserted individually instead.

Differences found (each is asserted below next to a ``DIFFERENCE(js)`` comment):

- Certainty: JS forwards the fact verbatim, so the body carries ``{"cf": "99"}`` (a string).
  Python accepts ``cf`` as input but sends a numeric ``certainty`` key (``99``).
- Auth: JS sends no credentials at all on ``/inject`` (only ``Content-Type``). Python sends
  ``X-API-Key`` on every request and never an ``Authorization`` header.
- Engine: JS passes ``{engine}`` per call; Python sets it once with ``Rainbird(engine=...)`` and
  sends ``x-rainbird-engine`` on every request.
- Empty facts: the JS error cases call ``inject(url, sid, [])`` and the empty list reaches the
  server. Python rejects an empty list locally with ``InvalidFactError`` before sending anything,
  so the HTTP error paths are exercised with one real fact instead.
- Errors: JS throws ``Error("API error code: N")`` / re-throws the fetch error. Python raises
  ``NotFoundError`` / ``ServerError`` / ``BadRequestError`` (``RainbirdAPIError`` subclasses with
  ``.status_code``, ``.message``, ``.errors``, ``.body``, ``.method``, ``.url``) and wraps the
  transport failure in ``RainbirdConnectionError`` (or ``RainbirdTimeoutError`` for an
  ``httpx.TimeoutException``) whose message embeds the original one.
- Return value: JS returns the parsed JSON as is; Python returns an ``InjectResponse`` that keeps
  the JSON on ``.raw`` / ``.to_dict()`` and exposes ``.result`` / ``.ok``.
"""

from __future__ import annotations

from typing import Any

import httpx
import pytest

from rainbird_ai import (
    BadRequestError,
    InjectResponse,
    InvalidFactError,
    NotFoundError,
    RainbirdAPIError,
    RainbirdConnectionError,
    RainbirdTimeoutError,
    RainbirdTransportError,
    ServerError,
    Session,
)
from tests.parity.support import (
    API_KEY,
    BASE_URL,
    Handler,
    Recorder,
    make_client,
    raise_transport_error,
    respond,
)

# The JS tests pass baseURL "thisIsTheURL" / "thisistheurl"; Python needs a real http(s) URL, so
# the helper's default (https://api.test) stands in for it. The session ids are kept verbatim.
SESSION_ID = "thisIsTheSessionID"
ERROR_SESSION_ID = "thisistheid"

# The canned JS fetch response, verbatim: `json: async () => ({ response: { ok: true } })`.
JS_OK_BODY: dict[str, Any] = {"response": {"ok": True}}

# The message of the error the JS mock fetch throws, verbatim.
FETCH_ERROR_MESSAGE = "This was generated by fetch"

# The fact used by the error cases so that a request is actually sent (see
# `_assert_empty_facts_rejected_locally`); the JS cases pass an empty list instead.
ONE_FACT: dict[str, Any] = {
    "cf": "99",
    "object": "England",
    "relationship": "lives in",
    "subject": "David",
}


def _session(handler: Handler, session_id: str, **kwargs: Any) -> tuple[Session, Recorder]:
    """A ``Session`` attached to ``session_id`` (no start call) plus the request recorder."""
    rb, rec = make_client(handler, **kwargs)
    return rb.resume(session_id), rec


def _assert_common_request_shape(rec: Recorder, session_id: str) -> None:
    """The assertions every happy-path JS case makes on ``global.fetch.mock.calls[0][1]``.

    All of them except one: ``expect(Object.keys(call).sort()).toEqual(["body", "headers",
    "method"])`` (inject.test.js:27, 83, 144) checks the shape of the jest fetch *init* object and
    has no httpx analogue, so it is deliberately not ported. Its intent, "the request is exactly a
    method, headers and a body, nothing else", is covered by asserting each of the three below.
    """
    # JS: expect(global.fetch).toHaveBeenCalledTimes(1)
    assert len(rec) == 1
    call = rec.last
    # JS: expect(call.method).toEqual("POST")
    assert call.method == "POST"
    # inject.ts: fetch(`${baseURL}/${sessionID}/inject`, ...)
    assert call.path == f"/{session_id}/inject"
    assert str(call.url) == f"{BASE_URL}/{session_id}/inject"
    # JS: expect(call.headers).toMatchObject({ "Content-Type": "application/json" })
    assert call.headers["content-type"] == "application/json"
    # DIFFERENCE(js): JS sends no credentials on /inject (its headers are exactly Content-Type
    # plus the optional engine). Python sends X-API-Key on every request and never Authorization.
    assert call.headers["x-api-key"] == API_KEY
    assert "authorization" not in call.headers


def _assert_js_ok_result(result: InjectResponse) -> None:
    """JS: ``expect(result).toEqual({ response: { ok: true } })``.

    Python wraps the body in :class:`InjectResponse` and keeps the JSON on ``.raw``. The canned
    body has no top-level ``result``/``ok``/``status`` key, so ``.result`` is ``None`` and ``.ok``
    is ``True`` by the "no result key means success" rule of ``InjectResponse.ok``.
    """
    assert isinstance(result, InjectResponse)
    assert result.raw == JS_OK_BODY
    assert result.to_dict() == JS_OK_BODY
    assert result.to_dict() is not result.raw  # deep copy, never the live object
    assert result.result is None
    assert result.ok is True


def _assert_empty_facts_rejected_locally(session: Session, rec: Recorder) -> None:
    """What ``inject(url, sid, [])`` (the JS error cases' input) does in Python."""
    # DIFFERENCE(js): JS forwards the empty list and the request reaches the server, so the HTTP
    # error is what surfaces. Python's normalize_facts() rejects an empty list before any request
    # is sent (InvalidFactError, no HTTP call), so the HTTP error paths below use ONE_FACT.
    with pytest.raises(InvalidFactError, match="facts must not be empty"):
        session.inject([])
    assert len(rec) == 0


# source: inject.test.js:9 should assert a new fact within a session
def test_should_assert_a_new_fact_within_a_session() -> None:
    session, rec = _session(respond(200, JS_OK_BODY), SESSION_ID)

    result = session.inject(
        [
            {
                "cf": "99",
                "object": "England",
                "relationship": "lives in",
                "subject": "David",
            },
        ]
    )

    _assert_common_request_shape(rec, SESSION_ID)
    # JS: expect(JSON.parse(call.body)).toMatchObject([{ cf: "99", object: "England",
    #     relationship: "lives in", subject: "David" }])
    # DIFFERENCE(js): JS forwards the fact verbatim, so the wire body carries "cf": "99" (a
    # string). Python accepts "cf" as an input alias but normalises it to a numeric "certainty".
    assert rec.last.json == [
        {"subject": "David", "relationship": "lives in", "object": "England", "certainty": 99},
    ]
    assert "cf" not in rec.last.json[0]
    assert isinstance(rec.last.json[0]["certainty"], int)
    _assert_js_ok_result(result)


