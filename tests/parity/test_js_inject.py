# source: inject.ts:8 interface InjectResponse { result: string; warningLog?: WarningLog[] }
def test_inject_response_interface_result_and_warning_log() -> None:
    """Not a JS test case: the shape ``inject.ts`` declares for the real API response.

    JS types the body as ``{result, warningLog?}`` and returns it as is. Python maps ``result``
    to ``InjectResponse.result``/``.ok`` and has no typed accessor for ``warningLog``; it is
    reachable only through ``.raw`` / ``.to_dict()`` (design rule: never lose API data).
    """
    body = {
        "result": "OK",
        "warningLog": [{"message": "duplicate fact ignored", "timestamp": "2024-01-01T00:00:00Z"}],
    }
    session, rec = _session(respond(200, body), SESSION_ID)

    result = session.inject([ONE_FACT])

    assert len(rec) == 1
    assert result.result == "OK"
    assert result.ok is True
    # warningLog has no typed accessor in Python today; it is preserved on .raw / .to_dict().
    assert result.raw["warningLog"] == body["warningLog"]
    assert result.to_dict() == body


# source: inject.test.js:13 canned body `{ response: { ok: true } }` (regression guard, not a case)
def test_inject_response_ok_ignores_nested_ok() -> None:
    """Not a JS test case: pins how ``InjectResponse.ok`` reads the JS mock body's *shape*.

    ``InjectResponse.from_dict`` only looks at the top-level ``result``/``ok``/``status`` keys and
    ``.ok`` is ``True`` whenever none of them is present ("no result key means success"). The JS
    fixture nests its flag under ``response``, so flipping it to ``false`` does not change what
    Python reports. The real API answers ``{"result": "OK"}``, which is why this is recorded as a
    possible bug (lenient success check) rather than asserted as the desired behaviour; if the
    check is ever tightened, this test is the one to update.
    """
    body = {"response": {"ok": False}}
    session, rec = _session(respond(200, body), SESSION_ID)

    result = session.inject([ONE_FACT])

    assert len(rec) == 1
    assert result.raw == body
    assert result.result is None
    # Possible bug: a nested `"ok": false` is invisible to the success check.
    assert result.ok is True
    # For contrast, the same flag at the top level is honoured.
    assert InjectResponse.from_dict({"ok": False}).ok is False
    assert InjectResponse.from_dict({"ok": True}).ok is True
    assert InjectResponse.from_dict({"result": "ERROR"}).ok is False
