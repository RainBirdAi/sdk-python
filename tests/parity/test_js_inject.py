# source: inject.test.js:121 should assert a facts for specific engine within a session
def test_should_assert_a_facts_for_specific_engine_within_a_session() -> None:
    # DIFFERENCE(js): JS passes `{ engine: "thisIsTheEngine" }` per call; Python configures the
    # engine once on the client and sends the header on every request.
    session, rec = _session(respond(200, JS_OK_BODY), SESSION_ID, engine="thisIsTheEngine")

    result = session.inject(
        [
            {
                "cf": "99",
                "object": "England",
                "relationship": "lives in",
                "subject": "David",
            },
        ]
    )

    _assert_common_request_shape(rec, SESSION_ID)
